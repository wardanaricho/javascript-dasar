// ==============================
// BOOLEAN DI JAVASCRIPT
// ==============================

// Boolean adalah tipe data yang hanya memiliki 2 nilai:
// true  → benar
// false → salah

// Boolean true
// Digunakan untuk menyatakan kondisi benar
console.log(true);
// Output: true


// Boolean false
// Digunakan untuk menyatakan kondisi salah
console.log(false);
// Output: false


// ==============================
// KEGUNAAN BOOLEAN
// ==============================

// Biasanya digunakan dalam kondisi (if, while, dll)

let isLogin = true;

if (isLogin) {
    console.log("User sudah login");
}
// Karena nilainya true, maka kode di dalam if akan dijalankan


let isAdmin = false;

if (isAdmin) {
    console.log("User adalah admin");
}
// Karena nilainya false, maka kode ini tidak dijalankan


// ==============================
// BOOLEAN DARI PERBANDINGAN
// ==============================

// Boolean sering dihasilkan dari operasi perbandingan

console.log(10 > 5);
// Output: true

console.log(10 < 5);
// Output: false

console.log(10 === 10);
// Output: true

console.log(10 === 5);
// Output: false


