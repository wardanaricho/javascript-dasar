// ==============================
// NUMBER DI JAVASCRIPT
// ==============================

// Angka tanpa desimal disebut integer
console.log(123);
// Output: 123

// Angka dengan desimal disebut floating point
console.log(12.3);
// Output: 12.3

// Notasi scientific (eksponen)
// format: angka e pangkat
// 12e3 artinya 12 × 10^3
console.log(12e3);
// Output: 12000

// 12e-3 artinya 12 × 10^-3
console.log(12e-3);
// Output: 0.012


// ==============================
// STRING (BUKAN NUMBER)
// ==============================

// Ini adalah string karena menggunakan tanda kutip
// Walaupun isinya angka, tetap dianggap teks
console.log("2");
// Output: 2
// Tipe data: string


// ==============================
// NUMBER ANNOTATION (FORMAT ANGKA LAIN)
// ==============================

// Decimal (basis 10) → format normal
console.log(2);
// Output: 2

// Hexadecimal (basis 16)
// diawali dengan 0x
// FF dalam hex = 255 dalam decimal
console.log(0xFF);
// Output: 255

// Octal (basis 8)
// diawali dengan 0o
// 10 dalam octal = 8 dalam decimal
console.log(0o10);
// Output: 8

// Binary (basis 2)
// diawali dengan 0b
// 10 dalam binary = 2 dalam decimal
console.log(0b10);
// Output: 2


// ==============================
// KESIMPULAN
// ==============================

// JavaScript mendukung berbagai format number:
// decimal      → 123
// float        → 12.3
// scientific   → 12e3
// hexadecimal  → 0xFF
// octal        → 0o10
// binary       → 0b10

// Semua ini tetap bertipe data: number
