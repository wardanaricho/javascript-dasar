// ==============================
// OPERATOR ARITMATIKA DI JAVASCRIPT
// ==============================

// Variabel result diinisialisasi dengan nilai 1 + 2
// Operator + digunakan untuk penjumlahan

let result = 1 + 2;
console.log(result); // 3
// 1 + 2 = 3


// Operator - digunakan untuk pengurangan
// result sekarang 3, lalu dikurangi 1

result = result - 1;
console.log(result); // 2
// 3 - 1 = 2


// Operator * digunakan untuk perkalian
// result sekarang 2, lalu dikali 2

result = result * 2;
console.log(result); // 4
// 2 × 2 = 4


// Operator / digunakan untuk pembagian
// result sekarang 4, lalu dibagi 2

result = result / 2;
console.log(result); // 2
// 4 ÷ 2 = 2


// Operator % digunakan untuk modulus (sisa bagi)
// result sekarang 2, lalu 2 % 2

result = result % 2;
console.log(result); // 0
// 2 dibagi 2 = 1 sisa 0


// ==============================
// DAFTAR OPERATOR ARITMATIKA
// ==============================

// +  → penjumlahan
// -  → pengurangan
// *  → perkalian
// /  → pembagian
// %  → modulus (sisa bagi)


// ==============================
// CONTOH MODULUS LAIN
// ==============================

console.log(5 % 2); // 1 → karena 5 ÷ 2 sisa 1
console.log(10 % 3); // 1 → karena 10 ÷ 3 sisa 1
console.log(8 % 2); // 0 → karena 8 ÷ 2 sisa 0


// ==============================
// KEGUNAAN MODULUS (PENTING)
// ==============================

// Mengecek bilangan genap
let angka = 4;
console.log(angka % 2); // 0 → genap

// Mengecek bilangan ganjil
angka = 5;
console.log(angka % 2); // 1 → ganjil


