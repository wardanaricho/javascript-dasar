// lebih dari
let result = 5 > 3;
console.log(result); // true

// kurang dari
result = 5 < 3;
console.log(result); // false

// lebih dari sama dengan
result = 5 >= 3;
console.log(result); // true

// kurang dari sama dengan
result = 5 <= 3;
console.log(result); // false

// sama dengan
result = 5 == 3;
console.log(result); // false

// sama dengan tipe data
result = 5 === 3;
console.log(result); // false

// tidak sama dengan
result = 5 != 3;
console.log(result); // true

// tidak sama dengan tipe data
result = 5 !== 3;
console.log(result); // true