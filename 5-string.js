// ==============================
// STRING DI JAVASCRIPT
// ==============================

// String adalah tipe data untuk teks
// Ditulis menggunakan tanda kutip ("") atau ('')

console.log("Richo Wardana");
// Output: Richo Wardana


// ==============================
// STRING CONCATENATION
// ==============================

// Concatenation artinya menggabungkan string
// Menggunakan operator +

console.log("Hello" + " " + "World");
// "Hello"  → string pertama
// " "      → spasi
// "World"  → string kedua
// Output: Hello World


// ==============================
// ESCAPE CHARACTER
// ==============================

// Escape character digunakan untuk membuat karakter khusus
// Diawali dengan tanda backslash (\)


// \n → newline (baris baru)
console.log("Richo \n Wardana");
// Output:
// Richo
// Wardana


// \t → tab (jarak tab)
console.log("Richo \t Wardana");
// Output:
// Richo     Wardana


// \" → tanda kutip dua di dalam string
console.log("Richo \"Wardana\"");
// Output:
// Richo "Wardana"


// \' → tanda kutip satu di dalam string
console.log("Richo \'Wardana\'");
// Output:
// Richo 'Wardana'


// \\ → backslash
console.log("Richo \\ Wardana");
// Output:
// Richo \ Wardana


// ==============================
// ESCAPE CHARACTER LAINNYA
// ==============================

